-- V2: reminders. One per appointment, created in the SAME transaction as the booking (nothing to forget, nothing to
-- reconcile: either the appointment and its reminder exist, or neither does).
--
-- PENDING   waiting to be sent (or to be retried after next_attempt_at)
-- SENT      the provider accepted it
-- FAILED    a human has to look at it: the provider refused it for good, or it ran out of attempts
-- CANCELLED the appointment no longer needs it (cancelled, done, missed)
--
-- next_attempt_at doubles as a LEASE: whoever picks a reminder pushes it a few minutes ahead before calling the
-- provider, so a second instance (or the next tick) skips it, and a crash only delays it.

CREATE TABLE reminder (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT       NOT NULL UNIQUE REFERENCES appointment ON DELETE CASCADE,
    status          VARCHAR(10)  NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'CANCELLED')),
    due_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    attempts        INTEGER      NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error      VARCHAR(200),
    sent_at         TIMESTAMP(6) WITH TIME ZONE,
    CHECK (status <> 'SENT' OR sent_at IS NOT NULL)
);

-- the poller reads only what is waiting
CREATE INDEX reminder_waiting_idx ON reminder (next_attempt_at, id) WHERE status = 'PENDING';
