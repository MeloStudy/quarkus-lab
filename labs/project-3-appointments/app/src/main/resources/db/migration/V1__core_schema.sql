-- V1: practitioners, treatments, working hours, patients and appointments.
-- The question of this project is "can two appointments overlap for the same practitioner?". The answer is
-- written HERE, as exclusion constraints, so that no code path, script or race can break it. The API checks
-- first only for the rules that need a friendly error (the grid, the working hours, the past); an overlap is left to the
-- database on purpose: a check followed by an insert is a race.

-- Lets an exclusion constraint combine "equal" (a bigint) with "overlaps" (a range) in one index.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE practitioner (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80)  NOT NULL CHECK (length(trim(name)) > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE treatment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(80) NOT NULL UNIQUE,
    -- the slot grid is 15 minutes (application setting); a treatment is a whole number of slots, at most 4 hours
    duration_minutes INTEGER     NOT NULL CHECK (duration_minutes BETWEEN 15 AND 240 AND duration_minutes % 15 = 0)
);

-- Working hours are LOCAL times of the clinic ("09:00 on Mondays"), not instants: they follow the clock of the
-- clinic through daylight saving changes. weekday follows ISO-8601: 1 = Monday ... 7 = Sunday.
CREATE TABLE working_hours (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practitioner_id BIGINT   NOT NULL REFERENCES practitioner ON DELETE CASCADE,
    weekday         SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
    start_time      TIME     NOT NULL,
    end_time        TIME     NOT NULL,
    CHECK (start_time < end_time),
    -- two blocks of the same day may not overlap (a lunch break is two blocks with a gap)
    CONSTRAINT working_hours_no_overlap EXCLUDE USING gist (
        practitioner_id WITH =,
        weekday WITH =,
        tsrange(DATE '2000-01-01' + start_time, DATE '2000-01-01' + end_time) WITH &&)
);

CREATE TABLE patient (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(80)  NOT NULL CHECK (length(trim(full_name)) > 0),
    email      VARCHAR(120) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX patient_email_lower_uq ON patient (lower(email));

CREATE TABLE appointment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practitioner_id BIGINT       NOT NULL REFERENCES practitioner,
    patient_id      BIGINT       NOT NULL REFERENCES patient,
    treatment_id    BIGINT       NOT NULL REFERENCES treatment,
    -- INSTANTS (timestamptz), never local times: a local time can be ambiguous or not exist at all
    starts_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ends_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status          VARCHAR(10)  NOT NULL CHECK (status IN ('BOOKED', 'CANCELLED', 'COMPLETED', 'NO_SHOW')),
    version         BIGINT       NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CHECK (ends_at > starts_at),
    -- Half-open ranges '[)': an appointment that ends at 10:00 and one that starts at 10:00 do not overlap.
    -- Only BOOKED rows count: cancelling an appointment frees its time.
    CONSTRAINT appointment_no_overlap_practitioner EXCLUDE USING gist (
        practitioner_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&) WHERE (status = 'BOOKED'),
    -- the same patient cannot be in two places at once either
    CONSTRAINT appointment_no_overlap_patient EXCLUDE USING gist (
        patient_id WITH =, tstzrange(starts_at, ends_at, '[)') WITH &&) WHERE (status = 'BOOKED')
);

-- The exclusion constraints already index (practitioner, range) and (patient, range); this one serves the list.
CREATE INDEX appointment_starts_at_idx ON appointment (starts_at, id);
