-- V1: projects, issues, comments and the audit trail.
-- Rules that the database can enforce are enforced here too (CHECKs, UNIQUE, NOT NULL): the API validates for
-- friendly errors, the schema guarantees that nothing else (a script, a bug, another service) can break them.

CREATE TABLE project (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(5)   NOT NULL UNIQUE CHECK (code ~ '^[A-Z]{2,5}$'),
    name        VARCHAR(80)  NOT NULL,
    -- the number the NEXT issue of this project gets; issue creation locks the project row to hand it out
    next_number INTEGER      NOT NULL DEFAULT 1 CHECK (next_number >= 1),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE issue (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT        NOT NULL REFERENCES project,
    number      INTEGER       NOT NULL CHECK (number >= 1),
    title       VARCHAR(120)  NOT NULL,
    description VARCHAR(2000),
    type        VARCHAR(10)   NOT NULL CHECK (type IN ('BUG', 'TASK', 'STORY')),
    priority    VARCHAR(10)   NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    status      VARCHAR(12)   NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    assignee    VARCHAR(40),
    version     BIGINT        NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- the backstop of the numbering: even if the lock were forgotten, two issues can never share a key
    UNIQUE (project_id, number),
    -- an issue that is being worked on has somebody working on it
    CHECK (status <> 'IN_PROGRESS' OR assignee IS NOT NULL)
);

CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT        NOT NULL REFERENCES issue,
    author     VARCHAR(40)   NOT NULL,
    body       VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE issue_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT       NOT NULL REFERENCES issue,
    kind       VARCHAR(20)  NOT NULL CHECK (kind IN ('CREATED', 'STATUS_CHANGED', 'ASSIGNEE_CHANGED', 'PRIORITY_CHANGED')),
    detail     VARCHAR(200) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
