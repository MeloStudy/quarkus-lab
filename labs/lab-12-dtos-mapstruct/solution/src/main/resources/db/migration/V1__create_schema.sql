-- V1: the schema exactly as Hibernate expects it (generated once from the entities, then reviewed).
-- Panache entities (id extends PanacheEntity) take their ids from "<table>_SEQ" sequences with
-- increment 50: the increment must match the entity's allocation size, and validate checks it.

CREATE SEQUENCE audit_entry_SEQ    START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE customer_order_SEQ START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE label_SEQ          START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE price_change_SEQ   START WITH 1 INCREMENT BY 50;

CREATE TABLE product (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100)  NOT NULL,
    name_key  VARCHAR(100)  NOT NULL UNIQUE,
    category  VARCHAR(255)  NOT NULL,
    price     NUMERIC(9, 2) NOT NULL,
    stock     INTEGER       NOT NULL
);

CREATE TABLE label (
    id   BIGINT      NOT NULL PRIMARY KEY,
    name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE product_label (
    product_id BIGINT NOT NULL REFERENCES product,
    label_id   BIGINT NOT NULL REFERENCES label,
    PRIMARY KEY (label_id, product_id)
);

-- SINGLE_TABLE inheritance: "outlet" only has a value for critic rows, "verifiedPurchase" for customer rows
CREATE TABLE review (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT       NOT NULL REFERENCES product,
    kind             VARCHAR(10)  NOT NULL CHECK (kind IN ('CRITIC', 'CUSTOMER')),
    rating           INTEGER      NOT NULL,
    comment          VARCHAR(500) NOT NULL,
    createdAt        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    outlet           VARCHAR(255),
    verifiedPurchase BOOLEAN
);

CREATE TABLE customer_order (
    id        BIGINT        NOT NULL PRIMARY KEY,
    productId BIGINT        NOT NULL,
    quantity  INTEGER       NOT NULL,
    total     NUMERIC(11, 2) NOT NULL,
    createdAt TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_entry (
    id        BIGINT       NOT NULL PRIMARY KEY,
    productId BIGINT       NOT NULL,
    outcome   VARCHAR(40)  NOT NULL,
    createdAt TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE price_change (
    id        BIGINT        NOT NULL PRIMARY KEY,
    productId BIGINT        NOT NULL,
    oldPrice  NUMERIC(9, 2) NOT NULL,
    newPrice  NUMERIC(9, 2) NOT NULL,
    changedAt TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
