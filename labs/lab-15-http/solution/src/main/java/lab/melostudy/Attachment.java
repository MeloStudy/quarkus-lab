package lab.melostudy;

import java.util.List;

import io.quarkus.hibernate.orm.panache.PanacheEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;

/** Metadata of an uploaded file. The bytes live in the storage directory under {@link #storedName}, never under the client's name. */
@Entity
public class Attachment extends PanacheEntity {

    @Column(nullable = false)
    public Long documentId;

    /** The name the client gave, reduced to a plain file name. Only used for display and for the download header. */
    @Column(nullable = false, length = 200)
    public String fileName;

    @Column(nullable = false, length = 100)
    public String contentType;

    public long size;

    /** The name on disk: generated by us (a UUID). */
    @Column(nullable = false, length = 60)
    public String storedName;

    public static List<Attachment> of(long documentId) {
        return list("documentId", documentId);
    }
}
